import fs from "node:fs/promises";
import crypto from "node:crypto";
import path from "node:path";
import { syncClientGuidelines } from "./sync-client-guidelines.mjs";
import { ensureLegacySocialProofMarkup } from "./revision-engine.mjs";
import {
  REVISION_TEMPLATE_BASELINE_PATH,
  revisionTemplatePaths,
  retiredRouteTemplatePaths,
} from "./revision-template-paths.mjs";

const args = Object.fromEntries(
  process.argv
    .slice(2)
    .reduce(
      (pairs, value, index, all) =>
        index % 2 === 0
          ? [...pairs, [value.replace(/^--/, ""), all[index + 1]]]
          : pairs,
      [],
    ),
);
const client = path.resolve(String(args.client || ""));
if (!client) throw new Error("--client is required.");
const config = JSON.parse(
  await fs.readFile(path.join(client, "src/site.config.json"), "utf8"),
);
const operations = config.revisionReport?.operations || [];
const kinds = new Set(operations.map((operation) => operation.kind));
const repository = path.resolve(new URL("..", import.meta.url).pathname);
const template = path.join(repository, "templates/client-site/src");
const files = revisionTemplatePaths(config);

function hasSocialProofInsertionPoint(source) {
  if (/<(?:PageSections|SocialProof)\b/u.test(source)) return true;
  return (
    /import Header from [^;]+;/u.test(source) &&
    /<section\b[^>]*id=["']services["'][^>]*>[\s\S]*?<\/section>/iu.test(source)
  );
}

function digest(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function validTemplatePath(value) {
  return (
    typeof value === "string" &&
    value.startsWith("src/") &&
    !value.includes("\\") &&
    value.split("/").every((part) => part && part !== "." && part !== "..")
  );
}

const baselinePath = path.join(client, REVISION_TEMPLATE_BASELINE_PATH);
let baseline;
try {
  baseline = JSON.parse(await fs.readFile(baselinePath, "utf8"));
} catch (error) {
  if (error.code === "ENOENT") baseline = { version: 1, files: {} };
  else if (error instanceof SyntaxError)
    throw new Error(
      "Manual attention required: .launchloom/revision-template-baseline.json is unreadable; refusing to overwrite revision template files.",
    );
  else throw error;
}
if (
  baseline?.version !== 1 ||
  !baseline.files ||
  Array.isArray(baseline.files) ||
  typeof baseline.files !== "object" ||
  !Object.entries(baseline.files).every(
    ([relative, hash]) =>
      validTemplatePath(relative) && /^[a-f0-9]{64}$/u.test(hash),
  )
) {
  throw new Error(
    "Manual attention required: .launchloom/revision-template-baseline.json is invalid; refusing to overwrite revision template files.",
  );
}

// Record the exact generated bytes on the first safe sync, then roll that
// baseline forward only after a destination matches it. Older sites without
// this manifest may only adopt the current template as their baseline when the
// file already matches byte-for-byte. Any other divergence is ambiguous and
// requires manual review rather than a destructive template refresh.
const knownBaselines = JSON.parse(
  await fs.readFile(
    path.join(repository, "scripts/revision-template-known-baselines.json"),
    "utf8",
  ),
);
const nextBaselineFiles = { ...baseline.files };
const copyPlan = [];
const removalPlan = [];
const unchangedFiles = [];
const narrowPatchFiles = [];
const baselineManagedFiles = new Set();
const conflicts = [];
const homepageRelative = "src/pages/index.astro";
if (kinds.has("set_social_proof")) {
  const homepageSourcePath = path.join(template, "pages/index.astro");
  const homepageSource = await fs.readFile(homepageSourcePath);
  const homepageDestination = path.join(client, homepageRelative);
  const existingHomepage = await fs
    .readFile(homepageDestination)
    .catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
  if (!hasSocialProofInsertionPoint(homepageSource.toString("utf8")))
    throw new Error(
      "Manual attention required: the shared homepage template has no safe social-proof insertion point.",
    );
  if (existingHomepage === null && !files.includes(homepageRelative)) {
    copyPlan.push({
      relative: homepageRelative,
      sourcePath: homepageSourcePath,
      destination: homepageDestination,
    });
    nextBaselineFiles[homepageRelative] = digest(homepageSource);
    baselineManagedFiles.add(homepageRelative);
  } else if (existingHomepage !== null) {
    const existingHomepageHash = digest(existingHomepage);
    if (!hasSocialProofInsertionPoint(existingHomepage.toString("utf8")))
      throw new Error(
        "Manual attention required: cannot safely insert social proof into src/pages/index.astro because its generated insertion point is missing.",
      );
    if (
      existingHomepageHash === digest(homepageSource) ||
      existingHomepageHash === baseline.files[homepageRelative]
    ) {
      nextBaselineFiles[homepageRelative] = existingHomepageHash;
      baselineManagedFiles.add(homepageRelative);
    } else if (!files.includes(homepageRelative)) {
      narrowPatchFiles.push(homepageRelative);
    }
  }
}
for (const relative of files) {
  const sourcePath = path.join(repository, "templates/client-site", relative);
  const destination = path.join(client, relative);
  const source = await fs.readFile(sourcePath);
  const sourceHash = digest(source);
  const existing = await fs.readFile(destination).catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (existing === null) {
    copyPlan.push({ relative, sourcePath, destination });
    nextBaselineFiles[relative] = sourceHash;
    baselineManagedFiles.add(relative);
    continue;
  }
  const existingHash = digest(existing);
  if (existingHash === sourceHash) {
    unchangedFiles.push(relative);
    nextBaselineFiles[relative] = sourceHash;
    baselineManagedFiles.add(relative);
    continue;
  }
  if (
    (baseline.files[relative] && existingHash === baseline.files[relative]) ||
    (!baseline.files[relative] &&
      knownBaselines.files[relative]?.includes(existingHash))
  ) {
    copyPlan.push({ relative, sourcePath, destination });
    nextBaselineFiles[relative] = sourceHash;
    baselineManagedFiles.add(relative);
    continue;
  }
  if (
    relative === homepageRelative &&
    kinds.has("set_social_proof") &&
    hasSocialProofInsertionPoint(existing.toString("utf8"))
  ) {
    narrowPatchFiles.push(relative);
    continue;
  }
  conflicts.push(relative);
}

// Retire only exact known generated routes. Client edits require manual review.
for (const relative of retiredRouteTemplatePaths) {
  const destination = path.join(client, relative);
  const existing = await fs.readFile(destination).catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (existing === null) continue;
  const hash = digest(existing);
  if (
    hash === baseline.files[relative] ||
    knownBaselines.files[relative]?.includes(hash)
  ) {
    removalPlan.push(destination);
    delete nextBaselineFiles[relative];
  } else conflicts.push(relative);
}

if (conflicts.length) {
  throw new Error(
    `Manual attention required: refusing to overwrite existing revision template files that differ from the known generated baseline (current LaunchLoom template). No template files were copied. Review: ${conflicts.join(", ")}`,
  );
}

const guidelinesWritten = await syncClientGuidelines(client);
if (args["guidelines-written"]) {
  const evidencePath = path.resolve(args["guidelines-written"]);
  const previous = JSON.parse(
    await fs.readFile(evidencePath, "utf8").catch((error) => {
      if (error.code === "ENOENT") return "[]";
      throw error;
    }),
  );
  await fs.writeFile(
    evidencePath,
    `${JSON.stringify([...new Set([...previous, ...guidelinesWritten])])}\n`,
  );
}

for (const { sourcePath, destination } of copyPlan) {
  await fs.mkdir(path.dirname(destination), { recursive: true });
  await fs.copyFile(sourcePath, destination);
}
for (const destination of removalPlan) await fs.unlink(destination);
// Upgrade only the known legacy canonical expression. Preserve any other
// client-authored layout changes; an unknown layout must fail the release gate
// rather than be overwritten during unrelated feedback.
const layoutFile = path.join(client, "src/layouts/SiteLayout.astro");
const legacyLayout = await fs.readFile(layoutFile, "utf8").catch((error) => {
  if (error.code === "ENOENT") return "";
  throw error;
});
const legacyCanonical =
  'const canonical = site.business.domain ? `https://${site.business.domain.replace(/^https?:\\/\\//, "").replace(/\\/$/, "")}${Astro.url.pathname}` : undefined;';
if (legacyLayout.includes(legacyCanonical)) {
  const templateLayout = await fs.readFile(
    path.join(template, "layouts/SiteLayout.astro"),
    "utf8",
  );
  const currentCanonical = templateLayout.match(
    /^const canonical = .*;$/mu,
  )?.[0];
  if (!currentCanonical)
    throw new Error("Shared canonical expression is missing.");
  const currentRobots = templateLayout
    .match(/^\s*\{noIndex && <meta name="robots"[^\n]+$/mu)?.[0]
    ?.trim();
  if (!currentRobots) throw new Error("Shared robots metadata is missing.");
  const migratedLayout = legacyLayout
    .replace(legacyCanonical, currentCanonical)
    .replace(
      /<\/head>/iu,
      legacyLayout.includes('name="robots"')
        ? "</head>"
        : `  ${currentRobots}\n  </head>`,
    );
  await fs.writeFile(layoutFile, migratedLayout, "utf8");
}
if (kinds.has("set_social_proof")) {
  const homepage = path.join(client, "src/pages/index.astro");
  const source = await fs.readFile(homepage, "utf8");
  const revised = ensureLegacySocialProofMarkup(source);
  if (revised !== source) {
    await fs.writeFile(homepage, revised, "utf8");
  } else if (!hasSocialProofInsertionPoint(source)) {
    throw new Error(
      "Manual attention required: cannot safely insert social proof into src/pages/index.astro because its generated insertion point is missing.",
    );
  }
  if (baselineManagedFiles.has("src/pages/index.astro"))
    nextBaselineFiles["src/pages/index.astro"] = digest(
      await fs.readFile(homepage),
    );
}
await fs.mkdir(path.dirname(baselinePath), { recursive: true });
await fs.writeFile(
  baselinePath,
  `${JSON.stringify({ version: 1, files: nextBaselineFiles }, null, 2)}\n`,
);
console.log(`revision_template_files=${files.join(",") || "none"}`);
console.log(
  `revision_template_copied=${copyPlan.map(({ relative }) => relative).join(",") || "none"}`,
);
console.log(
  `revision_template_unchanged=${unchangedFiles.join(",") || "none"}`,
);
console.log(
  `revision_template_narrow_patch=${narrowPatchFiles.join(",") || "none"}`,
);
