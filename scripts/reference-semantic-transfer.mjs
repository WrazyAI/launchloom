/**
 * Shared rule for separating a reference's formal design language from its
 * domain-specific subject matter.
 */
export const REFERENCE_SEMANTIC_TRANSFER_GUIDANCE = `
SEMANTIC SUBJECT TRANSFER
- Transfer formal visual mechanics: geometry, scale, placement, silhouette, negative space, crop, material, lighting, and section rhythm.
- Treat depicted products, people, devices, logos, and other subject matter as reference-specific, not as required motifs or signatures, unless the client's business genuinely offers that subject.
- For signatures and acceptance checks, describe the mechanic rather than the literal subject (for example, "large diagonal isolated focal object" rather than "phone").
- Adapt the focal subject to the client's real business while keeping the reference's composition. A gym may use a plate-loaded barbell or training equipment in an object-stage composition, not an unrelated phone.
- Do not reward or require literal subject copying when comparing the candidate to the reference.`;
